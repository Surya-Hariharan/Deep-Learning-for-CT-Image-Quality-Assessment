"""Structural compatibility check of the historical checkpoints against the registry model.

READ-ONLY and inference-free: each checkpoint file is opened for reading, its tensors' keys and
shapes are compared with a freshly constructed `resnet50_regression` model, and a strict
`load_state_dict` is attempted on that fresh model. No forward pass is run, no metric is
computed, and no checkpoint is modified (SHA-256 is recorded before and after).

Usage (from the repository root):
    python tools/inspect_checkpoint_compatibility.py
Writes docs/audit/checkpoint-compatibility.md and .json.
"""

from __future__ import annotations

import json
from pathlib import Path

import torch

from ct_iqa.config.schema import ModelConfig
from ct_iqa.models.registry import build_model
from ct_iqa.models.weights import sha256_file

CHECKPOINTS = [
    "experiments/001_resnet50_baseline/checkpoint/best.pt",
    "experiments/002_learning_rate_search/lr_1e-2/checkpoint/best.pt",
    "experiments/002_learning_rate_search/lr_1e-3/checkpoint/best.pt",
    "experiments/002_learning_rate_search/lr_1e-4/checkpoint/best.pt",
    "experiments/002_learning_rate_search/lr_1e-5/checkpoint/best.pt",
    "experiments/003_final_training/checkpoint/final.pt",
]


def inspect(path: str) -> dict:
    p = Path(path)
    row: dict = {"path": path}
    row["sha256_before"] = sha256_file(p)
    try:
        payload = torch.load(p, map_location="cpu", weights_only=True)
        row["loaded_weights_only"] = True
    except Exception as exc:  # pragma: no cover - reported, not hidden
        row["loaded_weights_only"] = False
        row["weights_only_error"] = f"{type(exc).__name__}: {exc}"[:300]
        payload = torch.load(p, map_location="cpu")
    state = payload["model_state_dict"] if isinstance(payload, dict) and "model_state_dict" in payload else payload
    row["payload_keys"] = sorted(payload.keys()) if isinstance(payload, dict) else ["<bare state dict>"]
    cfg = payload.get("config", {}) if isinstance(payload, dict) else {}
    row["stored_config_subset"] = {k: cfg.get(k) for k in ("dropout_p", "in_channels", "image_size",
                                                             "learning_rate", "selection_metric", "device")}
    row["epoch_index_0based"] = payload.get("epoch") if isinstance(payload, dict) else None
    row["checkpoint_type"] = payload.get("checkpoint_type") if isinstance(payload, dict) else None

    model, _ = build_model(ModelConfig(name="resnet50_regression", dropout_p=0.5, bn_eps=1.001e-5, in_channels=1))
    ref = model.state_dict()
    ck_keys, ref_keys = set(state), set(ref)
    row["n_checkpoint_keys"], row["n_model_keys"] = len(ck_keys), len(ref_keys)
    row["missing_in_checkpoint"] = sorted(ref_keys - ck_keys)
    row["unexpected_in_checkpoint"] = sorted(ck_keys - ref_keys)
    row["shape_mismatches"] = [
        {"key": k, "checkpoint": list(state[k].shape), "model": list(ref[k].shape)}
        for k in sorted(ck_keys & ref_keys) if tuple(state[k].shape) != tuple(ref[k].shape)
    ]
    row["dtype_mismatches"] = [k for k in sorted(ck_keys & ref_keys) if state[k].dtype != ref[k].dtype]
    try:
        model.load_state_dict(state, strict=True)
        row["strict_load"] = "OK"
    except Exception as exc:
        row["strict_load"] = f"FAILED: {type(exc).__name__}: {str(exc)[:400]}"
    row["sha256_after"] = sha256_file(p)
    row["unchanged"] = row["sha256_before"] == row["sha256_after"]
    row["compatible"] = (
        row["strict_load"] == "OK" and not row["missing_in_checkpoint"] and not row["unexpected_in_checkpoint"]
        and not row["shape_mismatches"] and not row["dtype_mismatches"] and row["unchanged"]
    )
    return row


def main() -> None:
    rows = [inspect(p) for p in CHECKPOINTS]
    out = Path("docs/audit")
    (out / "CHECKPOINT_COMPATIBILITY.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
    lines = [
        "# Checkpoint compatibility matrix",
        "",
        "Generated by `tools/inspect_checkpoint_compatibility.py`. Structural check only: tensor keys, shapes and",
        "dtypes versus a freshly built `resnet50_regression` model (dropout 0.5, 1 input channel), plus a strict",
        "`load_state_dict` into that fresh model. **No forward pass, no inference, no metrics.** Checkpoint files were",
        "opened read-only; SHA-256 was recorded before and after.",
        "",
        "| Checkpoint | Keys (ckpt/model) | Missing | Unexpected | Shape mismatches | Strict load | File unchanged | Compatible |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| `{r['path']}` | {r['n_checkpoint_keys']}/{r['n_model_keys']} | {len(r['missing_in_checkpoint'])} | "
            f"{len(r['unexpected_in_checkpoint'])} | {len(r['shape_mismatches'])} | {r['strict_load']} | "
            f"{r['unchanged']} | **{'YES' if r['compatible'] else 'NO'}** |"
        )
    lines += ["", "## Stored metadata", "", "| Checkpoint | checkpoint_type | epoch (0-based) | stored config subset | SHA-256 |", "|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| `{r['path']}` | {r['checkpoint_type']} | {r['epoch_index_0based']} | `{r['stored_config_subset']}` | `{r['sha256_before'][:16]}...` |")
    lines += ["", "Matching key names alone do not establish identical behavior: BatchNorm epsilon is not stored in a",
              "state_dict (see ADR-002). Structural compatibility is a necessary, not a sufficient, condition.", ""]
    (out / "checkpoint-compatibility.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
