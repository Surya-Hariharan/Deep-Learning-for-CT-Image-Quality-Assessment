"""Inspect every configured dataset and emit an inventory report.

Read-only: this script never creates, moves, modifies or deletes dataset files.
Supplementary to scripts/audit_dataset.py (which focuses specifically on
LDCT-IQAC per the dataset-audit requirements) -- this one covers all seven
configured datasets generically.

    python scripts/dataset/inspect_datasets.py
    python scripts/dataset/inspect_datasets.py --datasets ldctiqa --hash
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from ct_iqa.config.loader import dataset_config, reports_dir  # noqa: E402
from ct_iqa.data.validation import scan_directory  # noqa: E402
from ct_iqa.utils.paths import as_relative, project_root, resolve  # noqa: E402

DATASETS = ["png", "lidc_idri", "luna16", "lndb", "deeplesion", "cq500", "ldctiqa"]


def inspect_one(name: str, verify_archives: bool = True) -> dict:
    """Describe one dataset from its config plus a filesystem scan."""
    cfg = dataset_config(name)
    root = resolve(cfg["raw_root"])
    scan = scan_directory(root, verify_archives=verify_archives)

    if not scan.exists:
        status = "MISSING_DIRECTORY"
    elif scan.n_files == 0:
        status = "NOT_DOWNLOADED"
    elif scan.corrupt:
        status = "PRESENT_WITH_ISSUES"
    else:
        status = "PRESENT"

    return {
        "dataset": name,
        "long_name": cfg.get("long_name"),
        "role": cfg.get("role"),
        "location": as_relative(root),
        "status": status,
        "n_files": scan.n_files,
        "n_dirs": scan.n_dirs,
        "size_mb": scan.total_mb,
        "formats": scan.formats,
        "archives": [as_relative(a) for a in scan.archives],
        "corrupt": [[as_relative(p), d] for p, d in scan.corrupt],
        "unreadable": scan.unreadable,
        "sample_files": scan.sample_files,
        "declared_present": cfg.get("present", None),
    }


def undeclared_paths() -> list[str]:
    """Find data that exists on disk but belongs to no configured dataset.

    A downloaded dataset sitting outside data/raw/<name>/ would otherwise be
    invisible to the whole pipeline.
    """
    data_root = resolve("data")
    known = {resolve(dataset_config(n)["raw_root"]) for n in DATASETS}
    known |= {resolve(p) for p in ("data/raw", "data/interim", "data/processed", "data/manifests")}

    stray: list[str] = []
    for entry in data_root.iterdir():
        if entry.is_dir() and entry not in known:
            stray.append(as_relative(entry))
        elif entry.is_file() and entry.name != ".gitkeep":
            stray.append(as_relative(entry))
    for entry in (data_root / "raw").iterdir():
        if entry.resolve() not in known:
            stray.append(as_relative(entry))
    return sorted(stray)


def render_markdown(results: list[dict], stray: list[str]) -> str:
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    lines = [
        "# Dataset Inventory",
        "",
        f"Generated: {now}",
        "Generated by: `scripts/dataset/inspect_datasets.py` (read-only scan)",
        "",
        "| Dataset | Role | Location | Status | Files | Size (MB) | Formats |",
        "| --- | --- | --- | --- | ---: | ---: | --- |",
    ]
    for r in results:
        fmts = ", ".join(f"{k}:{v}" for k, v in sorted(r["formats"].items())) or "-"
        lines.append(
            f"| {r['dataset']} | {r['role']} | `{r['location']}` | {r['status']} "
            f"| {r['n_files']} | {r['size_mb']} | {fmts} |"
        )

    issues = [r for r in results if r["corrupt"] or r["unreadable"]]
    lines += ["", "## Issues", ""]
    if issues:
        for r in issues:
            lines.append(f"- **{r['dataset']}**")
            for path, detail in r["corrupt"]:
                lines.append(f"  - corrupt: `{path}` -- {detail}")
            for detail in r["unreadable"]:
                lines.append(f"  - unreadable: {detail}")
    else:
        lines.append("None detected.")

    lines += ["", "## Unrecognised paths under data/", ""]
    lines.append("\n".join(f"- `{s}`" for s in stray) if stray else "None.")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--datasets", nargs="*", default=DATASETS, choices=DATASETS)
    parser.add_argument("--no-verify-archives", action="store_true")
    parser.add_argument("--json-out", default="reports/dataset_inventory.json")
    parser.add_argument("--md-out", default="reports/dataset_inventory_generated.md")
    args = parser.parse_args()

    results = [inspect_one(n, not args.no_verify_archives) for n in args.datasets]
    stray = undeclared_paths()

    reports_dir().mkdir(parents=True, exist_ok=True)
    payload = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "project_root": str(project_root().name),
        "datasets": results,
        "unrecognised_paths": stray,
    }
    resolve(args.json_out).write_text(json.dumps(payload, indent=2), encoding="utf-8")
    resolve(args.md_out).write_text(render_markdown(results, stray), encoding="utf-8")

    for r in results:
        print(f"{r['dataset']:<12} {r['status']:<22} files={r['n_files']:<7} {r['size_mb']} MB")
    if stray:
        print(f"\nUnrecognised paths under data/: {stray}")
    print(f"\nWrote {args.json_out} and {args.md_out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
