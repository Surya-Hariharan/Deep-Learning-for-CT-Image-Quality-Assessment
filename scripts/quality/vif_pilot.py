"""Small-pilot validation of the canonical VIF pipeline on real LDCT-IQAC images.

Selects ~20-50 real LDCT-IQAC reference images (stratified across the
expert_score range), applies the Ohashi degradation grid to each using the
project's canonical degradation engine, computes VIF with the canonical
`vif_wavelet(profile="project")`, runs per-image diagnostics, and analyses
monotonicity, distribution, and low-texture instability -- to answer one
question before any full-scale generation: does the validated-but-not-
MATLAB-verified VIF implementation behave sanely on real CT images, not
just synthetic test patterns?

Does NOT generate the 169,000-image dataset, does NOT write to
data/manifests/quality_iqa_manifest.*, does NOT modify
data/raw/ldctiqa/ground_truth_score.json, and does NOT train anything.
All generated pixels/plots are written under data/interim/vif_pilot/,
which is covered by the project's .gitignore (`data/interim/**`) --
nothing generated by this script is committed.

Two parameters this pilot must supply that the canonical dataset
generator (scripts/quality/build_ohashi_dataset.py) deliberately refuses
to guess -- combined-degradation order and noise sigma_scale -- are given
explicit, clearly-labelled PILOT-ONLY provisional values below. This does
NOT resolve U-D01/U-D02 in docs/research_decisions.md for the full
dataset; that remains open and separately gated.

Usage:
    python scripts/quality/vif_pilot.py [--n-references 30] [--seed-offset 0]
"""

