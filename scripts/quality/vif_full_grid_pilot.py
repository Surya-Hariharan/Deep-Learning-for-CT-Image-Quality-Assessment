"""Full-grid VIF pilot: 100 LDCT-IQAC references x the COMPLETE Ohashi
degradation grid (12 noise + 12 blur + 144 noise+blur = 168 conditions each),
before any commitment to the full 1,000-reference / 169,000-image dataset.

Extends scripts/quality/vif_pilot.py (30 refs, reduced 3x3 combined subset)
by exercising the full 12x12 combined factorial this time -- the one part
of the grid the smaller pilot deliberately did not cover.

Does NOT generate the 169,000-image dataset, does NOT write to
data/manifests/quality_iqa_manifest.*, does NOT modify
data/raw/ldctiqa/ground_truth_score.json, and does NOT train anything.
Does NOT modify src/ct_iqa/vif/wavelet.py. All generated pixels/plots are
written under data/interim/vif_full_grid_pilot/ (gitignored via
`data/interim/**`) -- nothing generated by this script is committed.

Same PILOT-ONLY provisional parameters as the smaller pilot
(combination_order, sigma_scale) -- see module docstring below for why,
and docs/research_decisions.md items U-D01/U-D02 for the still-open
status these do not resolve.

Performance note: `vif_wavelet(profile="project")` and
`vif_wavelet_diagnostics(..., profile="project")` both build the same
steerable pyramids from scratch; calling both separately (as the smaller
pilot did) doubles the work for no benefit when diagnostics are wanted
anyway. Since the "project" profile aggregates via a plain sum
(VIFProfile.aggregation == "sum"), the final VIF score can be derived
directly from vif_wavelet_diagnostics()'s per-subband numerator/denominator
totals -- confirmed identical to calling vif_wavelet() directly (see
docs/vif_full_grid_pilot_report.md, Runtime section) -- so this script
calls diagnostics only, roughly halving per-image compute time.

Usage:
    python scripts/quality/vif_full_grid_pilot.py [--n-references 100] [--seed-offset 0]
"""

