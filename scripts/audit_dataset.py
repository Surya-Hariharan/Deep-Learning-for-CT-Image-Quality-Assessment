"""Audit the real, locally-downloaded LDCT-IQAC dataset.

Read-only: never copies, moves, or modifies image files. Inspects what is
actually on disk (no assumptions about structure) and writes a compact report
to docs/dataset_audit.md plus a machine-readable JSON companion.

    python scripts/audit_dataset.py

The dataset location is resolved via ct_iqa.data.loader (honouring the
LDCT_IQA_DATA_ROOT environment variable if set) -- never a hardcoded path.
"""

from __future__ import annotations

import json
import statistics
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from ct_iqa.config.loader import dataset_config, reports_dir  # noqa: E402
from ct_iqa.data.validation import find_duplicate_content, find_duplicate_filenames  # noqa: E402
from ct_iqa.utils.paths import as_relative, resolve  # noqa: E402

EXPECTED_EXTENSION = ".png"


def audit_ldctiqac() -> dict:
    cfg = dataset_config("ldctiqa")
    img_dir = resolve(cfg["images_dir"])
    labels_file = resolve(cfg["labels_file"])

    result: dict = {
        "dataset": "ldctiqa",
        "images_dir": as_relative(img_dir),
        "labels_file": as_relative(labels_file),
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }

    if not img_dir.is_dir():
        result["status"] = "MISSING"
        return result
    if not labels_file.is_file():
        result["status"] = "LABELS_MISSING"
        return result

    all_files = sorted(p for p in img_dir.iterdir() if p.is_file())
    image_files = [p for p in all_files if p.suffix.lower() == EXPECTED_EXTENSION]
    unexpected_files = [p.name for p in all_files if p.suffix.lower() != EXPECTED_EXTENSION]

    labels: dict[str, float] = json.loads(labels_file.read_text(encoding="utf-8"))

    extensions = Counter(p.suffix.lower() for p in all_files)

    from PIL import Image, UnidentifiedImageError

    dimensions = Counter()
    modes = Counter()
    corrupted: list[str] = []
    for p in image_files:
        try:
            with Image.open(p) as im:
                im.verify()
            with Image.open(p) as im:
                dimensions[im.size] += 1
                modes[im.mode] += 1
        except (UnidentifiedImageError, OSError) as exc:
            corrupted.append(f"{p.name}: {exc}")

    image_names = {p.name for p in image_files}
    label_names = set(labels)
    missing_scores = sorted(image_names - label_names)   # images without a label
    missing_images = sorted(label_names - image_names)    # labels without an image

    dup_filenames = find_duplicate_filenames(image_files)

    scores = list(labels.values())

    result.update(
        {
            "status": "OK" if not corrupted else "CORRUPTED_FILES_FOUND",
            "total_image_files": len(image_files),
            "total_files_in_dir": len(all_files),
            "extensions": {k: v for k, v in extensions.items()},
            "unexpected_files": unexpected_files,
            "dimensions": {f"{w}x{h}": n for (w, h), n in dimensions.items()},
            "modes": dict(modes),
            "corrupted_files": corrupted,
            "duplicate_filenames": {k: [p.name for p in v] for k, v in dup_filenames.items()},
            "score_count": len(labels),
            "missing_score_entries": missing_scores,
            "missing_image_entries": missing_images,
            "score_min": min(scores) if scores else None,
            "score_max": max(scores) if scores else None,
            "score_mean": round(statistics.mean(scores), 4) if scores else None,
            "score_median": statistics.median(scores) if scores else None,
            "score_stdev": round(statistics.pstdev(scores), 4) if len(scores) > 1 else None,
        }
    )
    return result


def audit_content_duplicates(result: dict) -> dict:
    """Optional, slower pass: SHA-256 duplicate content check."""
    cfg = dataset_config("ldctiqa")
    img_dir = resolve(cfg["images_dir"])
    image_files = sorted(p for p in img_dir.iterdir() if p.is_file() and p.suffix.lower() == EXPECTED_EXTENSION)
    dup_content = find_duplicate_content(image_files)
    result["duplicate_content_groups"] = {h: [p.name for p in v] for h, v in dup_content.items()}
    return result


def render_markdown(result: dict) -> str:
    lines = [
        "# Dataset Audit — LDCT-IQAC",
        "",
        f"Generated: {result['generated_at']}",
        "Generated by: `scripts/audit_dataset.py` (read-only)",
        f"Status: **{result['status']}**",
        "",
        "## Location",
        "",
        f"- Images: `{result['images_dir']}`",
        f"- Labels: `{result['labels_file']}`",
        "",
        "## Counts",
        "",
        f"- Total image files (`.png`): {result['total_image_files']}",
        f"- Total files in directory: {result['total_files_in_dir']}",
        f"- Extensions: {result['extensions']}",
        f"- Unexpected (non-`.png`) files: {result['unexpected_files'] or 'none'}",
        "",
        "## Image properties",
        "",
        f"- Dimensions: {result['dimensions']}",
        f"- Modes: {result['modes']}",
        "",
        "## Integrity",
        "",
        f"- Corrupted / unreadable files: {len(result['corrupted_files'])}"
        + (f" — {result['corrupted_files']}" if result["corrupted_files"] else ""),
        f"- Duplicate filenames: {len(result['duplicate_filenames'])}"
        + (f" — {result['duplicate_filenames']}" if result["duplicate_filenames"] else ""),
    ]
    if "duplicate_content_groups" in result:
        n = len(result["duplicate_content_groups"])
        lines.append(f"- Duplicate content (SHA-256): {n}" + (f" — {result['duplicate_content_groups']}" if n else ""))
    lines += [
        "",
        "## Score / label coverage",
        "",
        f"- Score count: {result['score_count']}",
        f"- Images without a score: {len(result['missing_score_entries'])}"
        + (f" — {result['missing_score_entries'][:20]}" if result["missing_score_entries"] else ""),
        f"- Scores without an image: {len(result['missing_image_entries'])}"
        + (f" — {result['missing_image_entries'][:20]}" if result["missing_image_entries"] else ""),
        "",
        "## Score distribution",
        "",
        f"- Min: {result['score_min']}",
        f"- Max: {result['score_max']}",
        f"- Mean: {result['score_mean']}",
        f"- Median: {result['score_median']}",
        f"- Std dev (population): {result['score_stdev']}",
        "",
        "---",
        "",
        "This report reflects the actual local dataset at the time it was generated. "
        "Re-run `python scripts/audit_dataset.py` after any change to the dataset.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    result = audit_ldctiqac()
    if result["status"] not in ("MISSING", "LABELS_MISSING"):
        result = audit_content_duplicates(result)

    reports_dir().mkdir(parents=True, exist_ok=True)
    json_path = resolve("docs/dataset_audit.json")
    md_path = resolve("docs/dataset_audit.md")
    json_path.write_text(json.dumps(result, indent=2, default=str), encoding="utf-8")
    md_path.write_text(render_markdown(result), encoding="utf-8")

    print(f"status: {result['status']}")
    for key in ("total_image_files", "score_count", "score_min", "score_max", "score_mean", "score_median"):
        if key in result:
            print(f"{key}: {result[key]}")
    print(f"\nWrote docs/dataset_audit.md and docs/dataset_audit.json")
    return 0 if result["status"] in ("OK",) else 1


if __name__ == "__main__":
    raise SystemExit(main())
